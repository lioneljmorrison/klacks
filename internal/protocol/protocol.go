// Package protocol defines the client wire protocol: the JSON frames sent
// over the WebSocket. docs/protocol.md is the client-facing description;
// keep the two in step.
//
// Every frame is one JSON object (one WebSocket text message) with a
// version "v" and a "type". Byte fields (header, ciphertext) are standard
// base64, as encoding/json encodes []byte. Unknown fields are ignored, so v1 can gain
// optional fields; anything incompatible bumps the version.
package protocol

import (
	"encoding/json"
	"errors"
	"fmt"

	"github.com/lioneljmorrison/klacks/internal/core"
	"github.com/lioneljmorrison/klacks/internal/store"
)

// Version is the only protocol version this server speaks.
const Version = 1

// MaxFrameSize is the largest frame a client may send. It fits a publish
// whose header and ciphertext together are core.MaxPayloadSize bytes:
// base64 of the whole payload, up to 4 bytes more for padding when it is
// split across two fields, and 1 KiB for the rest of the frame (three UUIDs,
// field names, version and type). Frames must not be padded with whitespace.
const MaxFrameSize = (core.MaxPayloadSize+2)/3*4 + 4 + 1024

// Type is a frame type.
type Type string

// Client-to-server frame types.
const (
	TypeSubscribe Type = "subscribe"
	TypeResume    Type = "resume"
	TypePublish   Type = "publish"
	TypeAck       Type = "ack"
)

// Server-to-client frame types.
const (
	TypeDeliver       Type = "deliver"
	TypeError         Type = "error"
	TypeMemberRemoved Type = "member_removed"
	TypeMembers       Type = "members"
)

// Decode errors. ErrorFor maps them to error frames.
var (
	ErrBadFrame           = errors.New("bad frame")
	ErrUnsupportedVersion = errors.New("unsupported protocol version")
	ErrUnknownType        = errors.New("unknown frame type")
)

// UUID is a store.UUID that encodes as a canonical 36-character string.
type UUID store.UUID

// MarshalText implements encoding.TextMarshaler.
func (u UUID) MarshalText() ([]byte, error) { return []byte(store.FormatUUID(store.UUID(u))), nil }

// UnmarshalText implements encoding.TextUnmarshaler. Only the canonical form
// is accepted (store.ParseUUID).
func (u *UUID) UnmarshalText(b []byte) error {
	id, err := store.ParseUUID(string(b))
	if err != nil {
		return err
	}
	*u = UUID(id)
	return nil
}

func (u UUID) zero() bool { return u == UUID{} }

// Envelope is the part every frame shares. Encode fills it in.
type Envelope struct {
	V    int  `json:"v"`
	Type Type `json:"type"`
}

func (e *Envelope) envelope() *Envelope { return e }

// Frame is one of *Subscribe, *Resume, *Publish, *Ack, *Deliver or *Error.
type Frame interface {
	envelope() *Envelope
	frameType() Type
}

// Subscribe asks for live delivery of a room's new messages.
type Subscribe struct {
	Envelope
	RoomID UUID `json:"room_id"`
}

// Resume asks for every message in a room after LastSeenSeq (0: from the
// start), then live delivery.
type Resume struct {
	Envelope
	RoomID      UUID  `json:"room_id"`
	LastSeenSeq int64 `json:"last_seen_seq"`
}

// Publish posts a message. MessageID is generated by the client. DeviceID is
// the sending device. Header and Ciphertext are opaque to the server; together
// they may be at most core.MaxPayloadSize bytes. Header may be empty;
// Ciphertext may not.
type Publish struct {
	Envelope
	RoomID     UUID   `json:"room_id"`
	MessageID  UUID   `json:"message_id"`
	DeviceID   UUID   `json:"device_id"`
	Header     []byte `json:"header,omitempty"`
	Ciphertext []byte `json:"ciphertext"`
}

// Ack confirms the client has every message in a room up to Seq.
type Ack struct {
	Envelope
	RoomID UUID  `json:"room_id"`
	Seq    int64 `json:"seq"`
}

// Deliver is one stored message. It carries every field clients need to
// rebuild the AEAD associated data (room_id, sender_id, device_id, seq),
// exactly as stored.
type Deliver struct {
	Envelope
	RoomID     UUID   `json:"room_id"`
	Seq        int64  `json:"seq"`
	MessageID  UUID   `json:"message_id"`
	SenderID   UUID   `json:"sender_id"`
	DeviceID   UUID   `json:"device_id"`
	Header     []byte `json:"header,omitempty"`
	Ciphertext []byte `json:"ciphertext"`
}

// Error reports a failed request. RoomID and MessageID, when set, name the
// request it answers.
type Error struct {
	Envelope
	Code      string `json:"code"`
	Message   string `json:"message"`
	RoomID    UUID   `json:"room_id,omitzero"`
	MessageID UUID   `json:"message_id,omitzero"`
}

// MemberRemoved tells a room's subscribers that User left the room,
// removed by Actor (Actor == User when they left). It is live-only: never
// replayed by resume, whose members frame carries the room's current
// member list instead (S-29). The client sending frame docs live in
// docs/protocol.md.
type MemberRemoved struct {
	Envelope
	RoomID UUID `json:"room_id"`
	User   UUID `json:"user"`
	Actor  UUID `json:"actor"`
}

// Members is a room's current member list, sent as part of the resume
// flow (S-29): a client returning from offline diffs it against the
// members it knows and reconciles the difference.
type Members struct {
	Envelope
	RoomID  UUID   `json:"room_id"`
	Members []UUID `json:"members"`
}

func (*Subscribe) frameType() Type     { return TypeSubscribe }
func (*Resume) frameType() Type        { return TypeResume }
func (*Publish) frameType() Type       { return TypePublish }
func (*Ack) frameType() Type           { return TypeAck }
func (*Deliver) frameType() Type       { return TypeDeliver }
func (*Error) frameType() Type         { return TypeError }
func (*MemberRemoved) frameType() Type { return TypeMemberRemoved }
func (*Members) frameType() Type       { return TypeMembers }

// Encode sets f's version and type and returns its JSON.
func Encode(f Frame) ([]byte, error) {
	*f.envelope() = Envelope{V: Version, Type: f.frameType()}
	return json.Marshal(f)
}

// Decode parses and validates a client-to-server frame. Errors wrap
// ErrBadFrame, ErrUnsupportedVersion or ErrUnknownType.
func Decode(b []byte) (Frame, error) {
	var env Envelope
	if err := json.Unmarshal(b, &env); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrBadFrame, err)
	}
	if env.V != Version {
		return nil, fmt.Errorf("%w: %d", ErrUnsupportedVersion, env.V)
	}
	var f Frame
	switch env.Type {
	case TypeSubscribe:
		f = new(Subscribe)
	case TypeResume:
		f = new(Resume)
	case TypePublish:
		f = new(Publish)
	case TypeAck:
		f = new(Ack)
	default:
		return nil, fmt.Errorf("%w: %q", ErrUnknownType, env.Type)
	}
	if err := json.Unmarshal(b, f); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrBadFrame, err)
	}
	if err := validate(f); err != nil {
		return nil, fmt.Errorf("%w: %s: %w", ErrBadFrame, env.Type, err)
	}
	return f, nil
}

func validate(f Frame) error {
	switch f := f.(type) {
	case *Subscribe:
		if f.RoomID.zero() {
			return errors.New("room_id is required")
		}
	case *Resume:
		if f.RoomID.zero() {
			return errors.New("room_id is required")
		}
		if f.LastSeenSeq < 0 {
			return errors.New("last_seen_seq must be >= 0")
		}
	case *Publish:
		switch {
		case f.RoomID.zero():
			return errors.New("room_id is required")
		case f.MessageID.zero():
			return errors.New("message_id is required")
		case f.DeviceID.zero():
			return errors.New("device_id is required")
		case len(f.Ciphertext) == 0:
			return errors.New("ciphertext is required")
		}
	case *Ack:
		if f.RoomID.zero() {
			return errors.New("room_id is required")
		}
		if f.Seq < 1 {
			return errors.New("seq must be >= 1")
		}
	}
	return nil
}

// Error codes.
const (
	CodeBadFrame           = "bad_frame"
	CodeUnsupportedVersion = "unsupported_version"
	CodeUnknownType        = "unknown_type"
	CodePayloadTooLarge    = "payload_too_large"
	CodeNotMember          = "not_member"
	CodeForbidden          = "forbidden"
	CodeRoomNotFound       = "room_not_found"
	CodeInvalidArgument    = "invalid_argument"
	CodeUnavailable        = "unavailable"
	CodeInternal           = "internal"
)

var codes = []struct {
	err    error
	code   string
	detail bool // the full error text is safe to send: it is about the client's own frame
}{
	{ErrBadFrame, CodeBadFrame, true},
	{ErrUnsupportedVersion, CodeUnsupportedVersion, true},
	{ErrUnknownType, CodeUnknownType, true},
	{core.ErrPayloadTooLarge, CodePayloadTooLarge, false},
	{core.ErrNotMember, CodeNotMember, false},
	{core.ErrForbidden, CodeForbidden, false},
	{core.ErrRoomNotFound, CodeRoomNotFound, false},
	{core.ErrInvalidArgument, CodeInvalidArgument, false},
}

// ErrorFor maps err to an error frame. A decode error keeps its full text,
// which says what was wrong with the frame. A core error gets its sentinel's
// text, without the wrapping context. A store outage or timeout
// (store.Unavailable) becomes "unavailable", which the client may retry
// (S-46). Anything else becomes "internal" with no detail, which belongs in
// the server log, not on the wire. The caller sets RoomID and MessageID.
func ErrorFor(err error) *Error {
	for _, c := range codes {
		if errors.Is(err, c.err) {
			msg := c.err.Error()
			if c.detail {
				msg = err.Error()
			}
			return &Error{Code: c.code, Message: msg}
		}
	}
	if store.Unavailable(err) {
		return &Error{Code: CodeUnavailable, Message: "store unavailable; retry"}
	}
	return &Error{Code: CodeInternal, Message: "internal error"}
}
